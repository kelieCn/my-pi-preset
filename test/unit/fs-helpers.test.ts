/** isManagedFile 的托管判定：只认文件头注释，且标记必须位于注释正文开头。 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { afterAll, describe, expect, it } from 'vitest';

import { isManagedFile } from '../../src/fs-helpers.js';
import { cleanup, tempDir } from '../helpers/sandbox.js';

afterAll(cleanup);

function file(name: string, lines: string[]): string {
  const dir = tempDir();
  const path = join(dir, name);
  writeFileSync(path, lines.join('\n'));
  return path;
}

describe('isManagedFile', () => {
  it('行注释在文件开头声明托管', () => {
    const path = file('herdr-agent-state.ts', [
      '// installed by herdr',
      '// managed by herdr; reinstalling or updating the integration overwrites this file.',
      '// @ts-nocheck',
      'import { join } from "node:path";',
    ]);

    expect(isManagedFile(path)).toBe(true);
  });

  it('文档注释里转述别的文件的托管情况不算（曾把本机扩展静默跳过）', () => {
    const path = file('herdr-question-blocked.ts', [
      '/**',
      ' * Give herdr something to report as `blocked`.',
      ' *',
      ' * `herdr-agent-state.ts` (installed by `herdr integration install pi`) derives',
      ' * working/idle from pi lifecycle hooks.',
      ' */',
      'export function activate() {}',
    ]);

    expect(isManagedFile(path)).toBe(false);
  });

  it('块注释正文开头的托管声明仍然算', () => {
    const path = file('banner.ts', [
      '/**',
      ' * Generated by codegen. Do not edit.',
      ' */',
      'export const x = 1;',
    ]);

    expect(isManagedFile(path)).toBe(true);
  });

  it('注释前缀也认 /* */ 单行与 shebang 之后的声明', () => {
    expect(isManagedFile(file('single.ts', ['/* generated by codegen */']))).toBe(true);
    expect(isManagedFile(file('cli.mjs', ['#!/usr/bin/env node', '// managed by foo', 'run();']))).toBe(true);
  });

  it('首个非注释行之后出现的字样不算', () => {
    const path = file('late.ts', [
      'export const x = 1;',
      '// installed by herdr',
    ]);

    expect(isManagedFile(path)).toBe(false);
  });

  it('同目录旁挂文件仍视为托管', () => {
    const dir = tempDir();
    writeFileSync(join(dir, 'probe.js'), 'console.log(1)');
    writeFileSync(join(dir, 'probe.js.agentd-hash'), 'abc');

    expect(isManagedFile(join(dir, 'probe.js'))).toBe(true);
  });

  it('读不到文件时返回 false', () => {
    expect(isManagedFile(join(tempDir(), 'nope.ts'))).toBe(false);
  });
});
