import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, renameSync, writeFileSync } from 'node:fs';
import { basename, dirname } from 'node:path';

/** 文件头出现这些字样说明该文件由别的工具托管，不归本项目管理。 */
const MANAGED_RE = /\b(installed|managed|generated)\s+by\b/i;
const MANAGED_HEAD_LINES = 30;

/** 被当作 pi 扩展的文件后缀。 */
export const EXTENSION_RE = /\.(ts|js|mjs|cjs)$/;

export function readJson<T>(path: string, fallback: T): T {
  if (!existsSync(path))
    return fallback;
  return JSON.parse(readFileSync(path, 'utf8')) as T;
}

export function writeJson(path: string, value: unknown): void {
  mkdirSync(dirname(path), { recursive: true });
  const tmp = `${path}.tmp-${process.pid}`;
  writeFileSync(tmp, `${JSON.stringify(value, null, 2)}\n`);
  renameSync(tmp, path);
}

export function listDirFiles(dir: string, filter: (name: string) => boolean = () => true): string[] {
  if (!existsSync(dir))
    return [];
  return readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isFile() && !entry.name.startsWith('.') && filter(entry.name))
    .map((entry) => entry.name)
    .sort();
}

/**
 * 这个文件是不是由别的工具托管的。两种信号：
 * 1. 文件头若干行里有 "installed by" / "managed by" / "generated by"；
 * 2. 同目录存在以该文件名开头的旁挂文件（如 agentd-probe.js.agentd-hash）。
 * 第二条刻意不写死工具名，这样新工具也能被认出来。
 */
export function isManagedFile(path: string): boolean {
  let text: string;
  try {
    text = readFileSync(path, 'utf8');
  }
  catch {
    return false;
  }
  const head = text.split('\n', MANAGED_HEAD_LINES).join('\n');
  if (MANAGED_RE.test(head))
    return true;
  try {
    const dir = dirname(path);
    const base = basename(path);
    return readdirSync(dir).some((name) => name !== base && name.startsWith(`${base}.`));
  }
  catch {
    return false;
  }
}

export function sameContent(a: string, b: string): boolean {
  try {
    return readFileSync(a, 'utf8') === readFileSync(b, 'utf8');
  }
  catch {
    return false;
  }
}

/**
 * 仓库里这个路径是否有未提交的改动。
 * sync 的方向是「家目录覆盖仓库」，如果仓库那份写着自己还没同步出去的修改，
 * 直接覆盖就是静默丢代码——必须先让用户知道。
 */
export function hasUncommittedChanges(repoRoot: string, relativePath: string): boolean {
  try {
    const status = execFileSync('git', ['-C', repoRoot, 'status', '--porcelain', '--', relativePath], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    });
    return status.trim().length > 0;
  }
  catch {
    // 没有 git 命令或不是仓库：保守起见不拦
    return false;
  }
}

/** 备份目录用的时间戳，形如 20261026-171305。 */
export function stamp(): string {
  const now = new Date();
  const pad = (value: number): string => String(value).padStart(2, '0');
  return [
    now.getFullYear(),
    pad(now.getMonth() + 1),
    pad(now.getDate()),
    '-',
    pad(now.getHours()),
    pad(now.getMinutes()),
    pad(now.getSeconds()),
  ].join('');
}

export function indent(items: string[]): string {
  return items.map((item) => `  ${item}`).join('\n');
}
